-- V1 - Schema "projects" (vedi docs/ARCHITETTURA.md, sezione 3.2)

CREATE TABLE project (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug             VARCHAR(100) NOT NULL UNIQUE,            -- usato nell'URL
    status           VARCHAR(20)  NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    featured         BOOLEAN      NOT NULL DEFAULT FALSE,
    start_date       DATE,
    end_date         DATE,
    repo_provider    VARCHAR(10)  NOT NULL DEFAULT 'NONE' CHECK (repo_provider IN ('GITHUB', 'GITLAB', 'NONE')),
    repo_path        VARCHAR(200),                            -- owner/nome
    demo_url         VARCHAR(500),
    cover_image_url  VARCHAR(500),
    sort_order       INT          NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          INT          NOT NULL DEFAULT 0,         -- optimistic locking JPA
    CHECK (repo_provider = 'NONE' OR repo_path IS NOT NULL)
);

CREATE TABLE project_translation (
    project_id  BIGINT       NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    lang        CHAR(2)      NOT NULL CHECK (lang IN ('it', 'en')),
    title       VARCHAR(150) NOT NULL,
    summary     VARCHAR(300),
    body_md     TEXT,
    PRIMARY KEY (project_id, lang)
);

CREATE TABLE tag (
    id    BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(50) NOT NULL,
    slug  VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE project_tag (
    project_id  BIGINT NOT NULL REFERENCES project (id) ON DELETE CASCADE,
    tag_id      BIGINT NOT NULL REFERENCES tag (id) ON DELETE CASCADE,
    PRIMARY KEY (project_id, tag_id)
);
CREATE INDEX idx_project_tag_tag_id ON project_tag (tag_id);

-- Scritta solo dal job di sincronizzazione con GitHub/GitLab
CREATE TABLE repo_stats (
    project_id        BIGINT       PRIMARY KEY REFERENCES project (id) ON DELETE CASCADE,
    stars             INT          NOT NULL DEFAULT 0,
    forks             INT          NOT NULL DEFAULT 0,
    primary_language  VARCHAR(50),
    languages         JSONB,                                  -- es. {"Java": 81.2, "HTML": 18.8}
    last_commit_at    TIMESTAMPTZ,
    synced_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    sync_error        VARCHAR(500)
);
