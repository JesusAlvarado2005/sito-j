-- ---------- PROFILO (una sola riga, garantita dal CHECK) ----------
CREATE TABLE profile (
    id            SMALLINT     PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    full_name     VARCHAR(100) NOT NULL,
    public_email  VARCHAR(255),
    location      VARCHAR(100),
    avatar_url    VARCHAR(500),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE profile_translation (
    profile_id  SMALLINT     NOT NULL REFERENCES profile (id) ON DELETE CASCADE,
    lang        CHAR(2)      NOT NULL CHECK (lang IN ('it', 'en')),
    headline    VARCHAR(200) NOT NULL,
    bio_md      TEXT,
    cv_url      VARCHAR(500),
    PRIMARY KEY (profile_id, lang)
);

-- ---------- LINK SOCIAL ----------
CREATE TABLE social_link (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR(20)  NOT NULL CHECK (type IN ('GITHUB', 'GITLAB', 'LINKEDIN', 'EMAIL', 'WEBSITE', 'OTHER')),
    url         VARCHAR(500) NOT NULL,
    label       VARCHAR(100),
    sort_order  INT          NOT NULL DEFAULT 0
);

-- ---------- ESPERIENZE LAVORATIVE ----------
CREATE TABLE experience (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company      VARCHAR(150) NOT NULL,
    company_url  VARCHAR(500),
    location     VARCHAR(100),
    start_date   DATE         NOT NULL,
    end_date     DATE,                         -- NULL = lavoro attuale
    sort_order   INT          NOT NULL DEFAULT 0,
    CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE experience_translation (
    experience_id   BIGINT       NOT NULL REFERENCES experience (id) ON DELETE CASCADE,
    lang            CHAR(2)      NOT NULL CHECK (lang IN ('it', 'en')),
    role            VARCHAR(150) NOT NULL,
    description_md  TEXT,
    PRIMARY KEY (experience_id, lang)
);

-- ---------- FORMAZIONE ----------
CREATE TABLE education (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution  VARCHAR(150) NOT NULL,
    start_date   DATE         NOT NULL,
    end_date     DATE,
    sort_order   INT          NOT NULL DEFAULT 0,
    CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE education_translation (
    education_id    BIGINT       NOT NULL REFERENCES education (id) ON DELETE CASCADE,
    lang            CHAR(2)      NOT NULL CHECK (lang IN ('it', 'en')),
    degree          VARCHAR(150) NOT NULL,
    description_md  TEXT,
    PRIMARY KEY (education_id, lang)
);

-- ---------- SKILL ----------
CREATE TABLE skill_category (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50) NOT NULL UNIQUE,   -- es. BACKEND, DATABASE, DEVOPS
    sort_order  INT         NOT NULL DEFAULT 0
);

CREATE TABLE skill_category_translation (
    category_id  BIGINT      NOT NULL REFERENCES skill_category (id) ON DELETE CASCADE,
    lang         CHAR(2)     NOT NULL CHECK (lang IN ('it', 'en')),
    name         VARCHAR(80) NOT NULL,
    PRIMARY KEY (category_id, lang)
);

CREATE TABLE skill (
    id           BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id  BIGINT      NOT NULL REFERENCES skill_category (id) ON DELETE CASCADE,
    name         VARCHAR(80) NOT NULL,          -- es. "Spring Boot" (non si traduce)
    level        SMALLINT    CHECK (level BETWEEN 1 AND 5),
    sort_order   INT         NOT NULL DEFAULT 0,
    UNIQUE (category_id, name)
);

-- Indici sulle foreign key (Postgres non li crea in automatico)
CREATE INDEX idx_skill_category_id ON skill (category_id);
